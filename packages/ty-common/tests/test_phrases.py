"""Phrase files and languages (spec §6.5): same keys and slots everywhere, drafts never served in `live`."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import pytest
import yaml

from ty_common import phrases as ph
from ty_common.settings import find_config_dir, get_settings

SLOT = re.compile(r"\{\w+\}")


def flat(d: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    out: dict[str, Any] = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flat(v, f"{prefix}{k}."))
        else:
            out[f"{prefix}{k}"] = v
    return out


def files() -> list[Path]:
    return sorted((find_config_dir() / "phrases").glob("*.yaml"))


def test_23_languages_with_unique_codes() -> None:
    codes = [x["code"] for x in ph.languages()]
    assert len(codes) == 23 and len(set(codes)) == 23
    assert {x["group"] for x in ph.languages()} == {"A", "B"}


@pytest.mark.parametrize("path", files(), ids=lambda p: p.stem)
def test_phrase_file_has_every_key_and_slot(path: Path) -> None:
    en = flat(yaml.safe_load((find_config_dir() / "phrases" / "en.yaml").read_text(encoding="utf-8")))
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    other = flat(doc)
    assert doc["status"] in ("draft", "approved")
    if doc["status"] == "approved":
        assert len(doc["reviewers"]) >= 2 and doc["reviewed_on"], "approval needs two reviewers and a date"
    for key, val in en.items():
        if not isinstance(val, str):
            continue
        assert key in other, f"{path.stem}: missing {key}"
        assert sorted(SLOT.findall(other[key])) == sorted(SLOT.findall(val)), f"{path.stem}: slots differ in {key}"


def test_every_slot_is_fillable() -> None:
    p, _ = ph.phrases("en-IN")
    filled = {
        "back_by": "09:00",
        "next_window": "14:00",
        "time": "09:00",
        "issuer": "INCOIS",
        "warning_name": "High wave alert",
        "distance_km": 12,
        "direction": "south",
        "harbour": "Rameswaram",
        "name": "Appa",
        "source": "IMD",
    }
    for key, val in flat(p).items():
        if isinstance(val, str):
            out = val.format(**filled)
            assert "{" not in out, key


def test_live_never_serves_a_draft(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(get_settings(), "env", "live")
    ph.load.cache_clear()
    try:
        assert ph.available_languages() == [x for x in ph.languages() if x["status"] == "released"]
        assert ph.load("en-IN") is None or ph.load("en-IN")["status"] == "approved"  # type: ignore[index]
    finally:
        ph.load.cache_clear()


def test_nearest_language_has_no_built_in_default() -> None:
    assert ph.nearest_language("ta") == "ta-IN"
    assert ph.nearest_language("ml-IN") == "ml-IN"
    assert ph.nearest_language("fr-FR") == ph.available_languages()[0]["code"]


def test_harbours_suggest_the_state_language() -> None:
    h = ph.harbour("rameswaram")
    assert h["suggested_language"] == "ta-IN" and h["lat"] == 9.288
    with pytest.raises(ValueError):
        ph.harbour("nowhere")
    bbox = (8.0, 10.5, 78.0, 80.5)
    assert all(bbox[0] <= x["lat"] <= bbox[1] and bbox[2] <= x["lon"] <= bbox[3] for x in ph.harbours().values())


def test_app_language_list_matches_config() -> None:
    """apps/app/src/i18n/languages.json is generated by scripts/i18n_draft.py --sync-only; it must not drift."""
    import json

    app = json.loads((find_config_dir().parent / "apps/app/src/i18n/languages.json").read_text(encoding="utf-8"))
    keep = ("code", "sarvam_code", "name", "group", "script", "rtl", "status")
    assert app == [{k: x[k] for k in keep} for x in ph.languages()]
